distribution_types = Table(
    "distribution_types",
    metadata,
    Column("id", Integer, primary_key=True, autoincrement=False),
    Column("name", String, nullable=False, unique=True),
    Column("distribution_type", String, nullable=False),
    Column("distribution_uri", String, key="uri", nullable=False, unique=True),
    Column("label", Boolean, nullable=False),
    Column("note", Text),
    Column("position", Integer, nullable=False),
    Column("created_at", DateTime(timezone=True), server_default=func.now()),
    Column("updated_at", DateTime(timezone=True), server_default=func.now()),
)
distributions = Table(
    "resource_distributions",
    metadata,
    Column("id", Integer, primary_key=True),
    Column("resource_id", String, nullable=False),
    Column(
        "distribution_type_id",
        Integer,
        ForeignKey("distribution_types.id", ondelete="RESTRICT"),
        nullable=False,
    ),
    Column("url", Text, nullable=False),
    Column("label", Text),
    Column("position", Integer, nullable=False),
    Column("import_distribution_id", String, key="import_id"),
    Column("created_at", DateTime(timezone=True), server_default=func.now()),
    Column("updated_at", DateTime(timezone=True), server_default=func.now()),
    UniqueConstraint(
        "resource_id", "distribution_type_id", "url", name="resource_distribution_identity"
    ),
)
imports = Table(
    "resource_imports",
    metadata,
    Column("id", Uuid, primary_key=True),
    Column("actor_id", Uuid, ForeignKey("actors.id"), nullable=False),
    Column("lifecycle_id", Uuid, ForeignKey("lifecycles.lifecycle_id")),
    Column("set_id", String(128), ForeignKey("sets.set_id")),
    Column("intake_batch_id", Uuid, ForeignKey("resource_intake_batches.id")),
    CheckConstraint(
        "set_id IS NOT NULL OR lifecycle_id IS NOT NULL OR intake_batch_id IS NOT NULL",
        name="resource_import_owner",
    ),
    Column("request_hash", String(64), nullable=False),
    Column("response", JSONB, nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
)
evidence = Table(
    "resource_import_evidence",
    metadata,
    Column("resource_id", String, primary_key=True),
    Column("import_id", Uuid, ForeignKey("resource_imports.id"), nullable=False),
    Column("source_record", JSONB, nullable=False),
    Column("warnings", ARRAY(Text), nullable=False),
)

projection_requests = Table(
    "resource_projection_requests",
    metadata,
    Column("resource_id", String, ForeignKey("resources.id"), primary_key=True),
    Column("resource_version", Integer, primary_key=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    Column("next_attempt_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
    Column("visible_at", DateTime(timezone=True)),
)
